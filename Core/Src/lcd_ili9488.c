/* Map ASCII char → font index, returns -1 if not in subset */
static int font_index(char c)
{
    if (c == ' ') return 0;
    if (c >= '0' && c <= '9') return 1 + (c - '0');
    if (c == ':') return 11;
    if (c >= 'A' && c <= 'Z') return 12 + (c - 'A');
    if (c == '.') return 38;
    if (c == '-') return 39;
    if (c == '/') return 40;
    if (c == '(') return 41;
    if (c == ')') return 42;
    if (c == '+') return 43;
    return -1;  // not in font, will render as space
}

#define FONT_W 8
#define FONT_H 16

/* ---- Draw a single character at (x,y) ---- */
static void LCD_DrawChar(uint16_t x, uint16_t y, char c, uint16_t color, uint16_t bg)
{
    int idx = font_index(c);
    if (idx < 0) idx = 0;  // missing → space

    LCD_CS_LOW();
    LCD_SetWindow(x, y, x + FONT_W - 1, y + FONT_H - 1);
    LCD_CS_LOW();
    LCD_DC_DATA();

    for (int row = 0; row < FONT_H; row++) {
        uint8_t bits = font_8x16[idx][row];
        for (int col = 0; col < FONT_W; col++) {
            uint16_t c_out = (bits & 0x80) ? color : bg;
            LCD_WriteByte((c_out >> 8) & 0xF8);
            LCD_WriteByte((c_out >> 3) & 0xFC);
            LCD_WriteByte(c_out << 3);
            bits <<= 1;
        }
    }
    LCD_CS_HIGH();
}

/* ---- Print string at (x,y), no wrapping ---- */
void LCD_Print(uint16_t x, uint16_t y, const char *str, uint16_t color, uint16_t bg)
{
    while (*str) {
        LCD_DrawChar(x, y, *str++, color, bg);
        x += FONT_W + 1;  // 1px spacing
    }
}
